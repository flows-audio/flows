#!/usr/bin/env node
// Generates ui/src/protocol.gen.ts from protocol/flows-protocol.json.
//   node protocol/generate.mjs          write the file
//   node protocol/generate.mjs --check  fail if the file is stale (CI)
import { readFileSync, writeFileSync } from 'node:fs';
import { checkReferences, loadProtocol } from './schema.mjs';

const output = new URL('../ui/src/protocol.gen.ts', import.meta.url);
const protocol = loadProtocol();
checkReferences(protocol);

const quote = value => JSON.stringify(value).replace(/"/g, "'");
const key = name => (/^[A-Za-z_$][\w$]*$/.test(name) ? name : quote(name));
const comment = (text, indent = '') => (text ? `${indent}/** ${text} */\n` : '');

function type(schema, indent = '') {
  if (schema.$ref) return schema.$ref.replace('#/$defs/', '');
  if (schema.oneOf) return schema.oneOf.map(part => type(part, indent)).join(' | ');
  if (schema.allOf) return schema.allOf.map(part => type(part, indent)).join(' & ');
  if ('const' in schema) return quote(schema.const);
  if (schema.enum) return schema.enum.map(quote).join(' | ');
  if (Array.isArray(schema.type)) return schema.type.map(t => type({ ...schema, type: t }, indent)).join(' | ');
  switch (schema.type) {
    case 'string': return 'string';
    case 'integer':
    case 'number': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': {
      const item = type(schema.items ?? {}, indent);
      return /[|&]/.test(item) ? `(${item})[]` : `${item}[]`;
    }
    case 'object': {
      const properties = Object.entries(schema.properties ?? {});
      if (!properties.length) return schema.properties ? 'Record<string, never>' : 'Record<string, unknown>';
      return `{\n${members(schema, `${indent}  `)}${indent}}`;
    }
    default: return 'unknown';
  }
}
function members(schema, indent) {
  const required = new Set(schema.required ?? []);
  return Object.entries(schema.properties ?? {})
    .map(([name, child]) => `${comment(child.description, indent)}${indent}${key(name)}${required.has(name) ? '' : '?'}: ${type(child, indent)};\n`)
    .join('');
}
function definition(name, schema) {
  const doc = comment(schema.description);
  if (schema.type === 'object' && schema.properties && Object.keys(schema.properties).length)
    return `${doc}export interface ${name} {\n${members(schema, '  ')}}\n`;
  // Interface extension keeps editor hovers readable for allOf [$ref, object].
  if (schema.allOf?.length === 2 && schema.allOf[0].$ref && schema.allOf[1].type === 'object')
    return `${doc}export interface ${name} extends ${type(schema.allOf[0])} {\n${members(schema.allOf[1], '  ')}}\n`;
  return `${doc}export type ${name} = ${type(schema)};\n`;
}

const methods = Object.entries(protocol.methods);
let text = `// Generated by protocol/generate.mjs from protocol/flows-protocol.json. Do not edit.\n`;
text += `/* eslint-disable */\n\nexport const PROTOCOL_VERSION = ${protocol.version};\n\n`;
for (const [name, schema] of Object.entries(protocol.$defs)) text += `${definition(name, schema)}\n`;
text += `export interface Methods {\n`;
for (const [name, method] of methods) {
  text += comment(`${method.summary} (${method.owner})`, '  ');
  text += `  ${quote(name)}: { params: ${type(method.params, '    ')}; result: ${type(method.result, '    ')} };\n`;
}
text += `}\nexport type MethodName = keyof Methods;\nexport type MethodOwner = ${Object.keys(protocol.owners).map(quote).join(' | ')};\n`;
text += `export const METHOD_OWNERS: Record<MethodName, MethodOwner> = {\n${methods.map(([name, method]) => `  ${quote(name)}: ${quote(method.owner)},`).join('\n')}\n};\n`;
text += `export const METHOD_TIMEOUTS: Record<MethodName, number> = {\n${methods.map(([name, method]) => `  ${quote(name)}: ${method.timeoutMs ?? 30000},`).join('\n')}\n};\n\n`;
text += `export interface Events {\n${Object.entries(protocol.events).map(([name, event]) => `${comment(event.summary, '  ')}  ${name}: ${type(event.payload)};`).join('\n')}\n}\nexport type EventName = keyof Events;\n`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(output, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== text) {
    console.error('ui/src/protocol.gen.ts is out of date. Run: npm run protocol --prefix ui');
    process.exit(1);
  }
} else writeFileSync(output, text);
