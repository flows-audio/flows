#!/usr/bin/env python3
"""Embed every file of a built UI folder into a C++ source for the native WebView.

The WebView serves whatever Vite produced (code-split chunks, workers, fonts,
icons), so the editor build can change shape without touching C++ or CMake.
Usage: embed_ui.py <dist-folder> <output.cpp>
"""
from __future__ import annotations

import sys
from pathlib import Path

MIME = {
    ".html": "text/html",
    ".js": "text/javascript",
    ".mjs": "text/javascript",
    ".css": "text/css",
    ".json": "application/json",
    ".map": "application/json",
    ".webmanifest": "application/manifest+json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
    ".wasm": "application/wasm",
    ".txt": "text/plain",
    ".md": "text/markdown",
}
# Browser-only deployment files never belong in the native bundle.
SKIP = {"_headers", "_redirects"}


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    dist, output = Path(sys.argv[1]), Path(sys.argv[2])
    files = sorted(p for p in dist.rglob("*") if p.is_file() and p.name not in SKIP and not p.name.startswith("."))
    if not any(p.relative_to(dist).as_posix() == "index.html" for p in files):
        print(f"embed_ui: {dist}/index.html is missing; build the UI first", file=sys.stderr)
        return 1
    lines = ['// Generated by tools/embed_ui.py. Do not edit.', '#include "FlowsUi.hpp"', "", "namespace FlowsUi {", "namespace {"]
    table = []
    for index, path in enumerate(files):
        data = path.read_bytes()
        rel = "/" + path.relative_to(dist).as_posix()
        mime = MIME.get(path.suffix.lower(), "application/octet-stream")
        name = f"file{index}"
        lines.append(f"const unsigned char {name}[] = {{")
        for start in range(0, len(data), 24):
            chunk = data[start:start + 24]
            lines.append("    " + ",".join(str(b) for b in chunk) + ",")
        lines.append("    0};")
        table.append(f'    {{"{rel}", "{mime}", {name}, {len(data)}}},')
    lines += ["}  // namespace", "const File files[] = {"] + table + ["};", f"const std::size_t count = {len(files)};", "}  // namespace FlowsUi", ""]
    text = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text() != text:
        output.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
